/**
 * Print detection precision/recall over tests/corpus, with 95% Wilson
 * confidence intervals. `--update` rewrites the committed baseline (do this
 * deliberately, when detection has improved).
 *   npm run eval                         # hand-labelled corpus
 *   npm run eval -- --generated          # synthetic corpus (npm run gen-corpus)
 *   npm run eval -- --generated --report # also write docs/DETECTION_REPORT.md
 *   npm run eval -- --update             # accept a new baseline
 */
import { writeFileSync } from 'node:fs';
import {
  evaluateCorpus,
  loadCorpus,
  toBaseline,
  wilson,
  BASELINE_PATH,
  GENERATED_BASELINE_PATH,
  GENERATED_DIR,
} from '../tests/corpus/evaluate.js';
import { PACKAGE_VERSION } from '../src/config/constants.js';

const generated = process.argv.includes('--generated');
const r = evaluateCorpus(generated ? loadCorpus(GENERATED_DIR) : loadCorpus());
const rows = Object.entries(r.byType).sort(([a], [b]) => a.localeCompare(b));
const pct = (x: number) => `${(x * 100).toFixed(1)}%`;
const pad = (s: string | number, n: number) => String(s).padEnd(n);

const table = rows.map(([t, s]) => {
  const [lo, hi] = wilson(s.found, s.expected);
  const precision = s.found + s.falsePositives ? s.found / (s.found + s.falsePositives) : 1;
  return { t, s, lo, hi, precision };
});

console.log(`Corpus: ${r.cases} cases${generated ? ' (synthetic)' : ''}\n`);
console.log(`${pad('type', 18)}${pad('expected', 10)}${pad('found', 8)}${pad('recall', 9)}${pad('95% CI', 18)}${pad('precision', 11)}false positives`);
for (const { t, s, lo, hi, precision } of table) {
  console.log(
    `${pad(t, 18)}${pad(s.expected, 10)}${pad(s.found, 8)}${pad(s.expected ? pct(s.recall) : '-', 9)}${pad(s.expected ? `${pct(lo)}–${pct(hi)}` : '-', 18)}${pad(pct(precision), 11)}${s.falsePositives}`,
  );
}
console.log(`\nTotal false positives: ${r.falsePositives}`);
if (r.misses.length && !generated) {
  console.log('\nMissed:');
  for (const m of r.misses) console.log(`  ${m.type.padEnd(10)} ${JSON.stringify(m.value)}  in ${JSON.stringify(m.text)}`);
}
if (r.extras.length && !generated) {
  console.log('\nFalse positives:');
  for (const x of r.extras) console.log(`  ${x.type.padEnd(10)} ${JSON.stringify(x.value)}  in ${JSON.stringify(x.text)}`);
}

if (process.argv.includes('--update')) {
  const path = generated ? GENERATED_BASELINE_PATH : BASELINE_PATH;
  writeFileSync(path, JSON.stringify(toBaseline(r), null, 2) + '\n');
  console.log(`\nBaseline written to ${path}`);
}

if (process.argv.includes('--report')) {
  const date = new Date().toISOString().slice(0, 10);
  const lines = [
    '# Detection report',
    '',
    `vela-privacy ${PACKAGE_VERSION}, ${date}. Built-in detectors only (no NER service, no detector packs). Generated by \`npm run eval -- --generated --report\`.`,
    '',
    `Corpus: ${r.cases} synthetic cases and ${table.reduce((a, x) => a + x.s.expected, 0)} labelled entities from \`scripts/gen-corpus.ts\` (seeded, reproducible). The templates cover KYC records, bank transfers, card payments, GST invoices, legal pleadings, medical notes, Hinglish chat, Indic-script names, sign-offs and negatives. A detected value counts only if its type and exact text match the label; anything else detected is a false positive.`,
    '',
    'Recall intervals are 95% Wilson score intervals. They describe this synthetic corpus, not your traffic: run the evaluation on a labelled sample of your own data before relying on a number.',
    '',
    '**Read these numbers as an upper bound.** The templates are regular, and four detection bugs this corpus found were fixed against it (UPI IDs at the end of a sentence, Hinglish phone cues, surname-led names, addresses running past the PIN code). The hand-labelled corpus in `tests/corpus/*.jsonl` (`npm run eval`) holds the harder cases, and its misses are listed there. An independent, human-labelled benchmark is still needed.',
    '',
    '| Type | Labelled | Found | Recall | 95% CI | Precision | False positives |',
    '|---|---:|---:|---:|---|---:|---:|',
    ...table.map(({ t, s, lo, hi, precision }) =>
      `| ${t} | ${s.expected} | ${s.found} | ${s.expected ? pct(s.recall) : '–'} | ${s.expected ? `${pct(lo)}–${pct(hi)}` : '–'} | ${pct(precision)} | ${s.falsePositives} |`,
    ),
    '',
    `Total false positives: ${r.falsePositives}.`,
    '',
    '## Known gaps',
    '',
    '- Names in Indic scripts are not detected by the built-in heuristics. Use an NER service (Presidio with an Indic model) and `ner: { required: true }`.',
    '- A bare first name with no surname or cue is detected only when it cannot be an ordinary word.',
    '- Address boundaries are heuristic; partial matches count as misses here even though most of the address is masked.',
    '',
  ];
  writeFileSync('docs/DETECTION_REPORT.md', lines.join('\n'));
  console.log('\nWrote docs/DETECTION_REPORT.md');
}
